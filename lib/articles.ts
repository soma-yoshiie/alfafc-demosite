import type { SavedDrill, SavedPlay, SavedSetPiece } from "./types";

export interface Article {
  id: string;
  category: string;
  title: string;
  lead: string;
  /** 本文（段落配列） */
  body: string[];
}

/** 記事に添付する戦術/練習/セットプレー（チャット添付と同じく埋め込みでライブラリ非依存） */
export interface ArticleAttachment {
  kind: "play" | "drill" | "setpiece";
  title: string;
  play?: SavedPlay;
  drill?: SavedDrill;
  setpiece?: SavedSetPiece;
}

/**
 * スタッフが投稿した記事。id は "u-" プレフィクスで seed("a-")と区別する。
 * draft=true は下書き（投稿画面の一覧にのみ表示。閲覧一覧・モバイルシートには出ない）
 */
export interface UserArticle extends Article {
  /** 掲載する名前 */
  author: string;
  ts: number;
  updatedAt: number;
  draft?: boolean;
  attachments?: ArticleAttachment[];
  /* ---- コーチラボ（後方互換の任意項目。既存データは未設定のまま読める） ---- */
  /** 指導者プロフィールのID。未設定なら閲覧時に投稿者本人（"me:<email>"相当）として扱う */
  authorId?: string;
  /** 最大5個 */
  tags?: string[];
  /** 0 or 未設定＝無料。有料は100〜50,000円 */
  price?: number;
  /** 有料ラインの位置＝この index 以降の段落が有料（null/未設定＝全文無料） */
  paidFrom?: number | null;
  /** 初回公開時刻 */
  publishedAt?: number;
  /** 購入後24時間以内の返金申請を受け付けるか（既定 true） */
  refundable?: boolean;
  /** 読者の想定（任意） */
  audience?: "coach" | "parent" | "player";
}

/** 閲覧一覧用: seed記事 + 公開済み投稿記事（新しい順で先頭に） */
export function mergedArticles(userArticles: UserArticle[]): Article[] {
  const published = userArticles
    .filter((a) => !a.draft)
    .sort((a, b) => b.updatedAt - a.updatedAt);
  return [...published, ...ARTICLES];
}

